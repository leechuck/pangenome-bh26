"""Builds REPORT.md tables from the row-level/summary TSVs (local, small tables)."""
import csv, collections, json
from pathlib import Path
R = Path(__file__).resolve().parent.parent / 'results'
rd = lambda n: list(csv.DictReader(open(R / n), delimiter='\t'))
S = rd('dose_summary_full.tsv'); K = rd('dose_contrasts_full.tsv'); G = rd('dose_by_gene_full.tsv'); rows = rd('dose_rows_full.tsv')
idx = {(r['group'], r['cell'], r['metric']): r for r in S}
def f(g, c, m, ci=True):
    r = idx.get((g, c, m))
    if not r or r['n'] in ('0', ''): return 'n/a'
    s = f"{r['k']}/{r['n']} = {float(r['pct']):.1f}%"
    return s + (f" [{float(r['lo']):.1f}, {float(r['hi']):.1f}]" if ci and r['lo'] != '' else '')
out = []
P = out.append
GR = [('ME', 'ME (Arab+Saudi), simulated reads'), ('EAS', 'East Asian, real reads'), ('SAS', 'South Asian, real reads')]
def cellorder(g):
    return ['n0', 'match_n05', 'match_n10', 'match_n20', 'match_n40'] + [f'x_{s}_n{n}' for s in ('ME', 'EAS', 'SAS', 'NONASIAN') if s != g for n in ('10', '40')] + ['B_existing']
def table(metric, title, ci=True):
    P(f'#### {title}\n')
    P('| cell | ' + ' | '.join(x[1] for x in GR) + ' |'); P('|---|' + '---|' * 3)
    for c in cellorder('X'):
        if c == 'n0' or c.startswith('match') or c == 'B_existing':
            P(f'| {c} | ' + ' | '.join(f(g, c, metric, ci) for g, _ in GR) + ' |')
    P('')
def cross(metric, title):
    P(f'#### {title}\n')
    P('| group | n | matched | from ME | from EAS | from SAS | from non-Asian HPRC |'); P('|---|---|---|---|---|---|---|')
    for g, _ in GR:
        for n in ('10', '40'):
            cells = [f'match_n{n}'] + [f'x_{s}_n{n}' if s != g else None for s in ('ME', 'EAS', 'SAS', 'NONASIAN')]
            P(f'| {g} | {n} | ' + ' | '.join('(matched)' if c is None else f(g, c, metric) for c in [cells[0]] ) + ' | ' + ' | '.join('-' if c is None else f(g, c, metric) for c in cells[1:]) + ' |')
    P('')
P('## Result tables (generated by src/s3_report.py from results/*.tsv)\n')
P('Intervals are family-clustered 95% bootstrap intervals (4000 resamples, FOLDS components as clusters, seed 20261020, as the frozen scorer). Each shared denominator is the same copies in every cell of a group.\n')
table('absent_exact_any', 'T1. IPD-absent copies recovered, byte-exact (sequence appears in any called slot, the frozen `recovered` definition)')
table('absent_body_any', 'T2. IPD-absent copies recovered, gene-body exact (first exon start to last exon end)')
table('absent_exact_final', 'T2b. IPD-absent copies recovered, byte-exact AND it is the slot\'s final call')
cross('absent_exact_any', 'T3. Matched vs cross-population panel at the same n, byte-exact recovery of IPD-absent copies')
cross('absent_body_any', 'T3b. Same, gene-body exact')
table('supplied_byte', 'T4. Ceiling: IPD-absent copies whose exact sequence is in the drawn panel (truth only, no typing)')
table('supplied_body', 'T4b. Ceiling, gene-body')
table('conv_exact_any', 'T5. Conversion = recovered / supplied by the panel (byte-exact; denominator = supplied copies)')
table('conv_body_any', 'T5b. Conversion, gene-body')
table('present_named4', 'T6. Four-field named correct among IPD-present copies (safety)')
table('all_correct', 'T7. Share of ALL scored copies fully correct (IPD-absent: exact in final call; IPD-present with one four-field truth label: named 4-field)')
P('Cross-population cells (same table, other sources) are in `results/dose_summary_full.tsv` / `figure_ready_dose_response.tsv`.\n')
# contrasts
P('### T8. Paired contrasts (same copies; percentage points of IPD-absent copies; sign-flip p from the frozen scorer)\n')
P('| group | kind | A vs B | metric | gains/losses | diff pp [95%] | p |'); P('|---|---|---|---|---|---|---|')
for r in K:
    if r['metric'] in ('absent_exact_any', 'absent_body_any') and r['kind'] != 'matched vs IPD only' or (r['metric'] == 'absent_exact_any' and r['kind'] == 'matched vs IPD only'):
        P(f"| {r['group']} | {r['kind']} | {r['cell_a']} vs {r['cell_b']} | {r['metric']} | {r['gains']}/{r['losses']} | {float(r['diff_pp']):+.2f} [{float(r['lo']):+.2f}, {float(r['hi']):+.2f}] | {r['sign_flip_p']} |")
P('')
P('### T9. Safety contrasts: IPD-present four-field named correct, matched cell minus IPD only (pp)\n')
P('| group | cell | gains/losses | diff pp [95%] |'); P('|---|---|---|---|')
for r in K:
    if r['metric'] == 'present_named4' and r['cell_b'] == 'n0':
        P(f"| {r['group']} | {r['cell_a']} | {r['gains']}/{r['losses']} | {float(r['diff_pp']):+.2f} [{float(r['lo']):+.2f}, {float(r['hi']):+.2f}] |")
P('')
# by gene
P('### T10. By gene: IPD-absent copies recovered (byte-exact), matched n=40 | supplied by that panel | IPD only (0 by construction), per group\n')
P('| group | ' + ' | '.join(['A', 'B', 'C', 'DPA1', 'DPB1', 'DQA1', 'DQB1', 'DRB1']) + ' |'); P('|---|' + '---|' * 8)
gi = {(r['group'], r['cell'], r['gene'], r['metric']): r for r in G}
for g, _ in GR:
    cells = []
    for gene in ['A', 'B', 'C', 'DPA1', 'DPB1', 'DQA1', 'DQB1', 'DRB1']:
        a = gi.get((g, 'match_n40', gene, 'absent_exact_any')); s = gi.get((g, 'match_n40', gene, 'supplied_byte'))
        cells.append(f"{a['k']}/{a['n']} | sup {s['k']}" if False else f"{a['k']} rec, {s['k']} sup, of {a['n']}" if a and s else '-')
    P(f'| {g} | ' + ' | '.join(cells) + ' |')
P('')
# real read sets split
P('### T11. Real reads split by read set (matched cells, byte-exact recovery of IPD-absent copies)\n')
P('| group | read set | donors | n0 | n=5 | n=10 | n=20 | n=40 |'); P('|---|---|---|---|---|---|---|---|')
for g in ('EAS', 'SAS'):
    for rs in ('T-real', 'D-real'):
        sel = [r for r in rows if r['group'] == g and r['readset'] == rs and r['ipd_absent'] == '1']
        d = len({r['donor'] for r in sel})
        def kk(c): 
            s = [r for r in sel if r['cell'] == c]; return f"{sum(int(r['recovered_any']) for r in s)}/{len(s)}"
        P(f"| {g} | {rs} | {d} | " + ' | '.join(kk(c) for c in ['n0', 'match_n05', 'match_n10', 'match_n20', 'match_n40']) + ' |')
P('')
open(R / 'report_tables.md', 'w').write('\n'.join(out))
print(len(out))
